/*
 * Dibujos de una sola línea (viewBox 0 0 160 160), sólo trazo.
 * Cada trazo lleva pathLength="1" para poder "dibujarlo" con stroke-dashoffset al aparecer.
 */
const p = (d: string) => `<path d="${d}" pathLength="1"/>`
const c = (cx: number, cy: number, r: number) => `<circle cx="${cx}" cy="${cy}" r="${r}" pathLength="1"/>`

function granos(): string {
  let s = p('M80 152 C80 120 79 80 82 22')
  for (const [i, y] of [36, 54, 72, 90].entries()) {
    const x = 80.5 + (i < 2 ? 1 : 0)
    s += p(`M${x} ${y + 14} C70 ${y + 10} 66 ${y} 69 ${y - 8} C77 ${y - 3} ${x} ${y + 4} ${x} ${y + 14}`)
    s += p(`M${x} ${y + 14} C91 ${y + 10} 95 ${y} 92 ${y - 8} C84 ${y - 3} ${x} ${y + 4} ${x} ${y + 14}`)
    s += p(`M69 ${y - 8} L60 ${y - 26}`) + p(`M92 ${y - 8} L101 ${y - 26}`)
  }
  s += p('M82 22 C83 16 84 12 86 6')
  // Una hoja larga que cae.
  s += p('M80 128 C92 118 108 116 122 120 C108 126 94 128 80 128')
  return s
}

function esparragos(): string {
  let s = ''
  for (const [x, top, inc] of [
    [58, 30, -6],
    [78, 18, 0],
    [98, 26, 6],
  ] as const) {
    s += p(`M${x - 4 + inc * 0.4} 150 C${x - 3} 110 ${x - 4} 70 ${x - 4 + inc * 0.3} ${top + 20}`)
    s += p(`M${x + 4 + inc * 0.4} 150 C${x + 5} 110 ${x + 4} 70 ${x + 4 + inc * 0.3} ${top + 20}`)
    s += p(`M${x - 4 + inc * 0.3} ${top + 20} C${x - 7} ${top + 8} ${x - 2} ${top} ${x + inc * 0.3} ${top - 4} C${x + 2} ${top} ${x + 7} ${top + 8} ${x + 4 + inc * 0.3} ${top + 20}`)
    for (const y of [top + 40, top + 66]) s += p(`M${x - 3} ${y} l3 -5 l3 5`)
  }
  // Atado de rafia.
  s += p('M48 118 C64 124 92 124 110 116') + p('M48 124 C64 130 92 130 110 122') + p('M100 120 C108 132 104 140 112 146')
  return s
}

